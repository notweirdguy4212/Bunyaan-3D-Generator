"""Convert Bunyaan occupancy volumes to meshes and export common 3D formats."""
from pathlib import Path
import numpy as np

def volume_to_mesh(volume, threshold=0.5):
    """Return vertices/faces from [D,H,W] occupancy. Requires scikit-image."""
    try: from skimage.measure import marching_cubes
    except ImportError as e: raise RuntimeError("Install scikit-image to extract meshes: pip install scikit-image") from e
    v=np.asarray(volume,dtype=np.float32).squeeze()
    if v.ndim!=3: raise ValueError("Expected a 3D occupancy volume")
    if not np.isfinite(v).all(): raise ValueError("Volume contains NaN/Inf")
    if v.max() <= threshold or v.min() >= threshold: raise ValueError("No surface found at this threshold; try another threshold or improve the model")
    verts,faces,normals,values=marching_cubes(v,level=threshold)
    # Normalize coordinates to a centered unit cube.
    verts=verts/(np.array(v.shape,dtype=np.float32)-1).clip(1)-0.5
    return verts.astype(np.float32),faces.astype(np.int32),normals.astype(np.float32)

def export_mesh(volume, path, threshold=0.5):
    path=Path(path); path.parent.mkdir(parents=True,exist_ok=True)
    verts,faces,normals=volume_to_mesh(volume,threshold)
    ext=path.suffix.lower()
    if ext=='.obj':
        with path.open('w') as f:
            f.write('# Generated by Bunyaan native 3D model\n')
            for x,y,z in verts: f.write(f'v {x:.7f} {y:.7f} {z:.7f}\n')
            for x,y,z in normals: f.write(f'vn {x:.7f} {y:.7f} {z:.7f}\n')
            for a,b,c in faces+1: f.write(f'f {a}//{a} {b}//{b} {c}//{c}\n')
    elif ext=='.ply':
        with path.open('w') as f:
            f.write('ply\nformat ascii 1.0\n')
            f.write(f'element vertex {len(verts)}\nproperty float x\nproperty float y\nproperty float z\n')
            f.write(f'element face {len(faces)}\nproperty list uchar int vertex_indices\nend_header\n')
            for v in verts: f.write(f'{v[0]} {v[1]} {v[2]}\n')
            for a,b,c in faces: f.write(f'3 {a} {b} {c}\n')
    elif ext in ('.glb','.gltf','.stl'):
        try: import trimesh
        except ImportError as e: raise RuntimeError("Install trimesh to export GLB/GLTF/STL: pip install trimesh") from e
        mesh=trimesh.Trimesh(vertices=verts,faces=faces,process=True); mesh.export(path)
    elif ext in ('.fbx','.usd','.usda','.usdc'):
        # Create an intermediate interchange mesh, then delegate to Blender's native exporter.
        import tempfile
        from .surface import export_interchange
        with tempfile.TemporaryDirectory() as td:
            intermediate=Path(td)/'mesh.glb'
            import trimesh
            trimesh.Trimesh(vertices=verts,faces=faces,process=True).export(intermediate)
            export_interchange(intermediate,path)
    else: raise ValueError("Supported formats: .obj, .ply, .glb, .gltf, .stl, .fbx, .usd, .usda, .usdc")
    return {"path":str(path),"vertices":int(len(verts)),"faces":int(len(faces)),"format":ext[1:]}
